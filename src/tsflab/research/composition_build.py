"""Turn a validated composition spec into a runnable config or a model package.

Used by ``tsf model compose --write-config`` and ``--register``. Nothing here
runs training: ``write_config`` emits one TOML run config (extends base + dataset
+ model preset) and ``register_model`` scaffolds an unregistered model workspace
that ``tsf model add --name NAME`` then admits and verifies.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path
from typing import Any

from tsflab.models._slots.registry import assignment_components, card_composition

#: Hyperparameters each adapter reads, with the defaults ``Pipeline`` uses.
HYPER_DEFAULTS: dict[str, object] = {
    "hidden": 16, "n_layers": 1, "n_heads": 4, "patch_len": 16, "stride": 8, "kernel_size": 25, "dropout": 0.0,
}
_HYPER_BY_TEMPORAL = {
    "linear": (),
    "channel_wise_linear": ("hidden",),
    "tst_transformer": ("hidden", "n_layers", "n_heads", "patch_len", "stride"),
    "mamba": ("hidden", "n_layers", "patch_len", "stride"),
    "gated_dilated_conv": ("hidden", "n_layers"),
    "mixer_block": ("hidden", "n_layers"),
}
#: Public symbol the generated model imports for each component (declaration/import audit).
IMPORT_SYMBOLS = {
    "channel_wise_linear": "ChannelWiseLinear",
    "flatten_forecast_head": "FlattenForecastHead",
    "gated_dilated_conv": "gated_dilated_conv",
    "gaussian_parameter_head": "GaussianParameterHead",
    "last_value_center": "center_on_last_value",
    "mamba": "MambaResidualBlock",
    "mixer_block": "MixerBlock",
    "positional_encoding": "positional_encoding",
    "quantile_head": "QuantileHead",
    "revin": "RevIN",
    "series_decomposition": "SeriesDecomposition",
    "tst_transformer": "TSTEncoder",
}
_FAMILY = {
    "linear": "linear", "channel_wise_linear": "linear", "tst_transformer": "transformer",
    "mamba": "ssm", "gated_dilated_conv": "cnn", "mixer_block": "mlp",
}
_NAME = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")


def _hyper(spec: dict[str, Any], assignment: dict[str, str]) -> dict[str, object]:
    allowed = set(HYPER_DEFAULTS)
    given = dict(spec.get("params", {}))
    unknown = sorted(set(given) - allowed - {"enc_in"})
    if unknown:
        raise ValueError(f"unknown [params] keys {unknown}; allowed {sorted(allowed | {'enc_in'})}")
    names = set(_HYPER_BY_TEMPORAL[assignment["temporal"]]) | {"dropout"}
    if assignment["decomposition"] == "series_decomposition":
        names.add("kernel_size")
    return {k: given.get(k, HYPER_DEFAULTS[k]) for k in HYPER_DEFAULTS if k in names or k in given}


def _toml_value(value: object) -> str:
    return json.dumps(value) if not isinstance(value, bool) else str(value).lower()


def _resolve_dataset(name: str | None, root: Path) -> Path:
    if not name:
        raise ValueError("--write-config needs --dataset (a TOML path or a configs/datasets preset name)")
    for candidate in (Path(name), root / name, root / "configs" / "datasets" / f"{name}.toml",
                      root / "configs" / "datasets" / f"{name.lower()}.toml"):
        if candidate.is_file():
            return candidate.resolve()
    raise ValueError(f"dataset config {name!r} not found (tried the path and configs/datasets/{name}.toml)")


def write_config(spec: dict[str, Any], result: dict[str, Any], opts: Any, root: Path) -> Path:
    """Write a runnable run config for the spec; returns its path."""
    executable = result["executable"]
    assignment = executable["assignment"]
    registered = opts.register
    if executable["output"] != "point" and not registered:
        raise ValueError(
            f"head {assignment['head']} gives {executable['output']} output; the Composed model is point-only. "
            "Add --register NAME so the config runs the dedicated model"
        )
    hyper = _hyper(spec, assignment)
    params = spec.get("params", {})
    enc_in = opts.enc_in or params.get("enc_in")
    if not enc_in:
        raise ValueError("pass --enc-in (channel count of the dataset) or set enc_in in the spec's [params]")
    out = Path(opts.write_config).resolve()
    dataset = _resolve_dataset(opts.dataset, root)
    base = (root / opts.base).resolve() if not Path(opts.base).is_absolute() else Path(opts.base)
    if not base.is_file():
        raise ValueError(f"base config {opts.base!r} not found under {root}")
    model_name = registered or "Composed"
    preset = root / "configs" / "models" / f"{model_name}.toml"
    rel = lambda p: os.path.relpath(p, out.parent)  # noqa: E731
    lines = [
        f"# Generated by `tsf model compose --write-config` from spec {spec.get('name')!r}.",
        f"extends = {json.dumps([rel(base), rel(dataset), rel(preset)])}",
        "",
        "[experiment]",
        f"description = {json.dumps('Composition ' + str(spec.get('name')) + ': ' + str(spec.get('hypothesis', '')).strip())}",
    ]
    if opts.work_dir:
        lines.append(f"work_dir = {json.dumps(str(opts.work_dir))}")
    if opts.smoke:
        lines += ["", "[experiment.runtime]", 'device = "cpu"', "num_workers = 0"]
    task = {k: v for k, v in (("seq_len", opts.seq_len), ("pred_len", opts.pred_len)) if v}
    if opts.smoke:
        task.setdefault("label_len", 0)
    if task:
        lines += ["", "[task]"] + [f"{k} = {v}" for k, v in task.items()]
    training: dict[str, object] = {"loss": assignment["loss"]}
    if opts.smoke:
        training.update(epochs=1, batch_size=16, patience=1)
    if opts.epochs:
        training["epochs"] = opts.epochs
    lines += ["", "[training]"] + [f"{k} = {_toml_value(v)}" for k, v in training.items()]
    lines += ["", "[model]", f"name = {json.dumps(model_name)}", "", "[model.params]", f"enc_in = {int(enc_in)}"]
    if not registered:
        lines += [f"{slot} = {json.dumps(assignment[slot])}" for slot in
                  ("normalization", "decomposition", "temporal", "channel", "head")]
    lines += [f"{k} = {_toml_value(v)}" for k, v in hyper.items()]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def _slug(name: str) -> str:
    return name.lower()


def _fits(spec: dict[str, Any], components: list[str]) -> list[str]:
    """Characteristics the composition targets: declared ``fits``, the hypothesis' rule id, or its components'."""
    from tsflab.catalog.cards.store import load
    from tsflab.catalog.characteristics import vocabulary
    from tsflab.core.paths import repository_root

    terms = set(vocabulary()) - {"any"}
    declared = [str(term) for term in spec.get("fits", []) if str(term) in terms]
    if declared:
        return declared
    head = str(spec.get("hypothesis", "")).split(":", 1)[0].strip()
    if head in terms:
        return [head]
    found: list[str] = []
    for component in components:
        try:
            card = load(repository_root() / "src" / "tsflab" / "models" / "_components" / component)
        except ValueError:
            continue
        found += [term for term in card.facts.get("fits", []) if term in terms and term not in found]
    if not found:
        raise ValueError("declare `fits = [...]` in the composition spec (characteristics it targets)")
    return found


def _files(spec: dict[str, Any], result: dict[str, Any], name: str) -> dict[str, str]:
    assignment = result["executable"]["assignment"]
    output = result["executable"]["output"]
    hyper = _hyper(spec, assignment)
    slug = _slug(name)
    comps = list(assignment_components(assignment))
    imports = "\n".join(
        f"from tsflab.models._components.{c} import {IMPORT_SYMBOLS[c]}  # noqa: F401" for c in comps
    )
    hypothesis = " ".join(str(spec.get("hypothesis", "")).split())
    summary = " ".join(str(spec.get("summary", "")).split())
    parents = sorted(set(result.get("parents", []) + result.get("donor_models", [])))
    tags = sorted({_FAMILY[assignment["temporal"]], "recombination", "autoresearch", "hybrid"})
    tagline = f"{name}: {assignment['temporal']} temporal, {assignment['normalization']} norm, {assignment['head']}"[:118]
    desc = {
        "point": "point", "quantile": "quantile-output", "distribution": "distribution-output",
    }[output]
    capabilities = ["time-series"] + ([] if output == "point" else [desc])
    hyper_fields = "\n".join(
        f"    {k}: {'float' if isinstance(v, float) else 'int'} = {v!r}" for k, v in hyper.items()
    )
    quantile = output == "quantile"
    if quantile:
        hyper_fields += "\n    quantile_levels: list[float] | None = None"
    option_names = {k: v for k, v in assignment.items() if k != "loss"}
    kwargs = ", ".join(f"{k}=params[{k!r}]" for k in hyper)
    if quantile:
        kwargs += (", " if kwargs else "") + "quantile_levels=params.get('quantile_levels') or list(cfg.evaluation.quantile_levels)"
    model_py = f'''"""{name}: a composition of cataloged components (generated by tsf model compose --register)."""

from __future__ import annotations

{imports}
from tsflab.models._slots.adapters import Pipeline

ASSIGNMENT = {{**{json.dumps(option_names)}, "loss": {json.dumps(assignment["loss"])}}}


class Model(Pipeline):
    """Fixed slot assignment {json.dumps(option_names)}."""

    def __init__(self, c_in: int, seq_len: int, pred_len: int, features: str = "M", **options) -> None:
        super().__init__(ASSIGNMENT, c_in, seq_len, pred_len, **options)
        self.features = features

    def forward(self, x_enc, x_mark_enc=None, x_dec=None, x_mark_dec=None):
        y = super().forward(x_enc, x_mark_enc, x_dec, x_mark_dec)
        return y[:, :, -1:] if self.features == "MS" else y
'''
    spec_py = f'''"""Model specification for {name}."""

from __future__ import annotations

from pydantic import BaseModel, Field

from tsflab.catalog.registry.models import ModelSpec
from tsflab.models.{slug}.model import Model


class ModelParameterConfig(BaseModel):
    enc_in: int = Field(gt=0)
{hyper_fields}


def build_model(cfg, params):
    """Construct {name} from a validated run configuration."""
    return Model(
        c_in=params["enc_in"],
        seq_len=cfg.task.seq_len,
        pred_len=cfg.task.pred_len,
        features=cfg.task.features,
        {kwargs},
    )


SPEC = ModelSpec(
    name={name!r},
    model_class=Model,
    factory=build_model,
    params_schema=ModelParameterConfig,
    capabilities=frozenset({capabilities!r}),
    components={tuple(comps)!r},
    contract_task={{"seq_len": 96, "pred_len": 96, "label_len": 0}},
)
'''
    composition = card_composition(assignment)
    ideas = [
        "Composition: " + ", ".join(f"{k}={v}" for k, v in option_names.items()) + f"; loss {assignment['loss']}.",
        f"Hypothesis: {hypothesis}",
        "Borrowed from: " + (", ".join(parents) if parents else "no named parent") + ".",
        "Built from the shared slot adapters in `tsflab.models._slots`; each component keeps its documented interface.",
    ]
    from tsflab.catalog.cards.render import card_files

    card = card_files("model", {
        "name": name,
        "tags": tags,
        "fits": _fits(spec, comps),
        "fidelity": "composed",
        "composition": dict(str(entry).split("=", 1) for entry in composition),
        "issues_checked": "recombination of cataloged components; no upstream paper or official code",
        "admission": {"status": "pending"},
    }, summary or tagline, {
        "Idea": "\n".join(f"- {line}" for line in ideas),
        "When to use": f"- Hypothesis under test: {hypothesis or 'not stated'}.",
        "Configure": f"Other hyperparameters: preset defaults in `configs/models/{name}.toml`; tune generically.",
        "Differences": "Not a paper reproduction: a recombination generated by `tsf model compose --register`.",
    })
    preset = "\n".join(
        ["[model]", f"name = {json.dumps(name)}", "", "[model.params]", f"enc_in = {int(spec.get('params', {}).get('enc_in', 7))}"]
        + [f"{k} = {_toml_value(v)}" for k, v in hyper.items()]
    ) + "\n"
    return {
        f"src/tsflab/models/{slug}/__init__.py": f'"""{name} model package."""\n',
        f"src/tsflab/models/{slug}/model.py": model_py,
        f"src/tsflab/models/{slug}/spec.py": spec_py,
        f"src/tsflab/models/{slug}/README.md": card["README.md"],
        f"src/tsflab/models/{slug}/card.toml": card["card.toml"],
        f"configs/models/{name}.toml": preset,
    }


def register_model(spec: dict[str, Any], result: dict[str, Any], name: str, root: Path, *, dry_run: bool) -> dict[str, Any]:
    """Scaffold a dedicated model package from the spec; returns the file list and next step."""
    from tsflab.catalog.registry.models import MODEL_CATALOG

    if not _NAME.match(name):
        raise ValueError("--register name must be alphanumeric and start with a letter")
    if name in set(MODEL_CATALOG.names()):
        raise ValueError(f"model {name!r} already exists in the catalog")
    files = _files(spec, result, name)
    package = root / "src" / "tsflab" / "models" / _slug(name)
    if package.exists():
        raise ValueError(f"{package} already exists")
    if not dry_run:
        for rel, text in files.items():
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    return {
        "dry_run": dry_run,
        "files": sorted(files),
        "next": f"tsf model add --name {name}",
    }
